type Props =
    | {
          defaultOpenKey?: string;
          items: FaqItem[];
          sections?: never;
      }
    | {
          defaultOpenKey?: string;
          items?: never;
          sections: FaqSection[];
      };

export function FaqAccordion({ defaultOpenKey, items, sections }: Props) {
    const normalizedSections: FaqSection[] = sections ?? [
        { title: '', items: items ?? [] },
    ];
    const firstKey =
        defaultOpenKey ??
        normalizedSections
            .flatMap((section, sectionIndex) =>
                section.items.map(
                    (item, itemIndex) =>
                        `${sectionIndex}:${itemIndex}:${item.question}`,
                ),
            )
            .at(0) ??
        null;

    const [openKey, setOpenKey] = useState<string | null>(firstKey);

    return (
        <>
            {normalizedSections.map((section, sectionIndex) => (
                <article
                    className={section.title ? 'faq-group-card' : undefined}
                    key={section.title || `section-${sectionIndex}`}
                >
                    {section.title ? <h2>{section.title}</h2> : null}
                    <div className="faq-list">
                        {section.items.map((item, itemIndex) => {
                            const itemKey = `${sectionIndex}:${itemIndex}:${item.question}`;

                            return (
                                <details
                                    key={itemKey}
                                    open={openKey === itemKey}
                                >
                                    <summary
                                        onClick={(event) => {
                                            event.preventDefault();
                                            setOpenKey((currentKey) =>
                                                currentKey === itemKey
                                                    ? null
                                                    : itemKey,
                                            );
                                        }}
                                    >
                                        {item.question}
                                    </summary>
                                    <p>{item.answer}</p>
                                </details>
                            );
                        })}
                    </div>
                </article>
            ))}
        </>
    );
}
